/**
 * SocialLinks 元件
 *
 * 顯示社群媒體連結的圖示列表
 * 支援 Facebook、Instagram、YouTube、LINE、Email
 *
 * @example
 * <SocialLinks links={siteConfig.socialLinks} size="md" theme="light" />
 */
export function SocialLinks({
  links,
  size = 'md',
  theme = 'light',
  className,
}: SocialLinksProps) {
  const sizeClasses = {
    sm: 'w-5 h-5',
    md: 'w-6 h-6',
    lg: 'w-8 h-8',
  };

  const themeClasses = {
    light: 'text-brand-black hover:text-brand-orange',
    dark: 'text-brand-white hover:text-brand-orange',
  };

  return (
    <div className={cn('flex items-center gap-4', className)}>
      {links.map((link) => (
        <a
          key={link.platform}
          href={link.url}
          target="_blank"
          rel="noopener noreferrer"
          aria-label={link.ariaLabel || getPlatformLabel(link.platform)}
          className={cn(
            'transition-colors duration-200',
            'focus:outline-none focus:ring-2 focus:ring-offset-2 focus:ring-brand-orange',
            'rounded-sm',
            themeClasses[theme]
          )}
        >
          <div className={sizeClasses[size]}>
            {getPlatformIcon(link.platform)}
          </div>
        </a>
      ))}
    </div>
  );
}
