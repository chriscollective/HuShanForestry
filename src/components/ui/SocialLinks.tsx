import type { JSX } from 'react';
import { SocialLink, SocialPlatform } from '@/types/social';
import { cn } from '@/lib/utils';

export interface SocialLinksProps {
  /**
   * 社群媒體連結陣列
   */
  links: ReadonlyArray<SocialLink>;

  /**
   * 圖示尺寸
   * sm: 小尺寸 (20px)
   * md: 中尺寸 (24px)
   * lg: 大尺寸 (32px)
   */
  size?: 'sm' | 'md' | 'lg';

  /**
   * 圖示顏色主題
   * light: 淺色主題（黑色圖示）
   * dark: 深色主題（白色圖示）
   */
  theme?: 'light' | 'dark';

  /**
   * 自訂 className
   */
  className?: string;
}

/**
 * 取得社群平台的 aria-label
 */
function getPlatformLabel(platform: SocialPlatform): string {
  const labels: Record<SocialPlatform, string> = {
    facebook: '前往 Facebook 粉絲專頁',
    instagram: '前往 Instagram 帳號',
    youtube: '前往 YouTube 頻道',
    line: '加入 LINE 官方帳號',
    email: '寄送電子郵件',
  };
  return labels[platform];
}

